"""Overview 页面：项目定位、边界说明。"""

import streamlit as st


def show():
    st.header("项目概览")

    st.markdown(
        """
        ## 项目定位

        **制造现场异常复盘与改善闭环工作台** 面向 IE 工程师 / 生产运营 / 质量工程师，
        用于将生产停机、OEE 和异常记录从原始事件标准化为可复盘、可分类、可跟踪的改善材料。

        ## 核心流程

        ```
        OEE / 停机事件 / 生产异常记录
                ↓
        统一制造异常事件模型
                ↓
        损失计算与 Pareto 分析
                ↓
        异常文本标准化 + 相似事件检索
                ↓
        改善项闭环跟踪
                ↓
        IE 周报 / 质量 CAPA / 5Why 草稿生成
        ```

        ## 系统边界

        ### 本项目做什么
        - 多数据源导入（Maven、Kaggle、通用 Excel）
        - 统一事件模型转换
        - 停机损失分析与 Pareto
        - 异常备注标准化（LLM 辅助）
        - 相似历史异常检索（Embedding）
        - 改善项闭环跟踪
        - IE 周报 / 质量 CAPA / 5Why 草稿生成

        ### 本项目不做什么
        - 不做自动排产 / 知识图谱
        - 不做自动根因判定
        - 不做 MES / OEE / QMS 替代品
        - 不做预测性维护 / 强化学习
        - 不让 LLM 直接生成数值结论

        ## LLM API 介入边界

        | 环节 | 谁来做 |
        |------|--------|
        | 数值计算 | Python（确定性） |
        | 异常备注标准化 | LLM API 辅助 |
        | 相似事件检索 | Embedding + FAISS |
        | 报告草稿生成 | LLM API |
        | 最终判断 | **人工确认** |

        ## 数据源说明

        | 数据源 | 用途 |
        |--------|------|
        | Maven Manufacturing Downtime | IE 视角主数据、停机损失分析 |
        | Kaggle OEE / Downtime | 质量视角增强、OEE 分析 |
        | 合成异常备注 | 演示文本标准化、相似检索流程 |
        | 合成改善项 | 演示改善闭环跟踪 |

        > **注意**：合成数据为 demo synthetic notes，不是企业真实生产数据。
        """
    )

show()
